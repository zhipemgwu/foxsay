/** 取关卡固定开场白（没有则返回 null，调用方可回退到 AI 生成） */
export function getFixedOpening(levelId: number | string): string | null {
  const idNum = typeof levelId === 'number' ? levelId : parseInt(String(levelId), 10);
  if (!Number.isFinite(idNum)) return null;
  return levelOpeningLines[idNum] ?? null;
}
