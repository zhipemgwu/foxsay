// ---------- 哈希：id 转确定性数字 ----------
function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

// ---------- 重写每题 ----------
let replaced = 0;
for (const q of bank) {
  const pool = POOLS[q.category];
  if (!pool) continue;

  // 取出原始正确选项
  const correct = q.options.find(o => o.isCorrect);
  if (!correct) continue;

  // 从 pool 中按 id hash 选 3 个不同的干扰项
  const base = hash(q.id);
  const picked = [];
  const used = new Set();
  let step = 1;
  while (picked.length < 3) {
    const idx = (base + step * 7) % pool.length;
    if (!used.has(idx)) {
      used.add(idx);
      picked.push(pool[idx]);
    }
    step++;
    if (step > 200) break;
  }

  // 正确答案本身也复用原文案（若没有，则提供一个通用兜底，实际上都有）
  const correctExplain = correct.explain && correct.explain.trim().startsWith('✅')
    ? correct.explain
    : '✅ 这样答是对的。稳情绪、守边界、表达清晰，是最安全的回应。';

  // 组装 4 个选项：3 干扰 + 1 正确
  const all = [
    { text: correct.text, isCorrect: true, explain: correctExplain },
    ...picked.map(p => ({ text: p.text, isCorrect: false, explain: p.explain })),
  ];

  // 按 id hash 做确定性洗牌，让正确答案不总在同一位置
  let s = hash(q.id) || 1;
  const rand = () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s; };
  const order = [0, 1, 2, 3];
  for (let i = 3; i > 0; i--) {
    const j = rand() % (i + 1);
    [order[i], order[j]] = [order[j], order[i]];
  }
  q.options = order.map(i => all[i]);

  q.overallExplain = OVERALL[q.category] || q.overallExplain;
  replaced++;
}

