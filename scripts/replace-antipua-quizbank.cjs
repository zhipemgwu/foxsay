function balanceTexts(sourceOptions, correctIndex, seed) {
  const options = sourceOptions.slice();
  const used = new Set();
  for (let round = 0; round < 12; round++) {
    const lens = options.map(textLen);
    const correctLen = lens[correctIndex];
    const wrongIndexes = options.map((_, i) => i).filter(i => i !== correctIndex);
    const wrongLens = wrongIndexes.map(i => lens[i]);
    const maxLen = Math.max(...lens);
    const minLen = Math.min(...lens);
    const wrongMax = Math.max(...wrongLens);
    const wrongMin = Math.min(...wrongLens);
    const correctUniqueMax = correctLen === maxLen && lens.filter(n => n === maxLen).length === 1;
    const shouldBreakLongestPattern = correctUniqueMax && seed % 5 !== 0;
    if (
      maxLen - minLen < 35 &&
      maxLen / Math.max(1, minLen) < 1.8 &&
      correctLen - wrongMax < 12 &&
      correctLen / Math.max(1, wrongMax) < 1.25 &&
      wrongMin - correctLen < 12 &&
      wrongMin / Math.max(1, correctLen) < 1.25 &&
      !shouldBreakLongestPattern
    ) {
      return options;
    }

    let targetIndex = lens.indexOf(minLen);
    if (shouldBreakLongestPattern) {
      targetIndex = wrongIndexes[wrongLens.indexOf(wrongMin)];
    } else if (correctLen - wrongMax >= 12 || correctLen / Math.max(1, wrongMax) >= 1.25) {
      targetIndex = wrongIndexes[wrongLens.indexOf(wrongMin)];
    } else if (wrongMin - correctLen >= 12 || wrongMin / Math.max(1, correctLen) >= 1.25) {
      targetIndex = correctIndex;
    }
    appendTail(options, targetIndex, seed + round + targetIndex, used);
  }
  return options;
}

function appendTail(options, index, seed, used) {
  const tails = tailsFor(options[index]);
  for (let offset = 0; offset < tails.length; offset++) {
    const tail = tails[(seed + offset) % tails.length];
    if (!used.has(tail) && !options[index].includes(tail)) {
      options[index] = `${options[index]}${tail}`;
      used.add(tail);
      return;
    }
  }
}

function textLen(text) {
  return Array.from(String(text || '').replace(/\s+/g, '')).length;
}

function validate(questions) {
  if (questions.length !== 50) throw new Error(`expected 50 anti-pua questions, got ${questions.length}`);
  const scenarios = new Set();
  const prompts = new Set();
  for (const q of questions) {
    if (scenarios.has(q.scenario)) throw new Error(`duplicate scenario: ${q.scenario}`);
    if (prompts.has(q.prompt)) throw new Error(`duplicate prompt: ${q.prompt}`);
    scenarios.add(q.scenario);
    prompts.add(q.prompt);
    if (q.options.length !== 4) throw new Error(`${q.id}: expected 4 options`);
    if (q.options.filter(o => o.isCorrect).length !== 1) throw new Error(`${q.id}: expected 1 correct option`);
    if (q.options.some(o => o.explain !== '')) throw new Error(`${q.id}: option explain should be empty`);
    if (q.options.some(o => /它能缓和|它既有态度|这次先围绕|会把关键边界|不把话题扩大/.test(o.text))) {
      throw new Error(`${q.id}: option text still contains meta explanation`);
    }
    const lens = q.options.map(o => textLen(o.text));
    const correctLen = textLen(q.options.find(o => o.isCorrect).text);
    const wrongLens = q.options.filter(o => !o.isCorrect).map(o => textLen(o.text));
    const maxLen = Math.max(...lens);
    const minLen = Math.min(...lens);
    const wrongMax = Math.max(...wrongLens);
    const wrongMin = Math.min(...wrongLens);
    if (maxLen - minLen >= 35 || maxLen / Math.max(1, minLen) >= 1.8) {
      throw new Error(`${q.id}: option length spread too wide (${minLen}-${maxLen})`);
    }
    if (correctLen - wrongMax >= 12 || correctLen / Math.max(1, wrongMax) >= 1.25) {
      throw new Error(`${q.id}: correct option length leaks (${correctLen} vs ${wrongMax})`);
    }
    if (wrongMin - correctLen >= 12 || wrongMin / Math.max(1, correctLen) >= 1.25) {
      throw new Error(`${q.id}: correct option too short (${correctLen} vs ${wrongMin})`);
    }
  }
}

