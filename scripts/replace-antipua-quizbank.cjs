function loadBank() {
  const source = fs.readFileSync(BANK_PATH, 'utf8');
  const start = source.indexOf(MARKER);
  if (start < 0) throw new Error('QUIZ_BANK marker not found');
  const jsonStart = start + MARKER.length;
  const end = source.indexOf(END_MARKER, jsonStart);
  if (end < 0) throw new Error('QUIZ_BANK end marker not found');
  const tail = source.slice(end + 2);
  return { bank: JSON.parse(source.slice(jsonStart, end)), tail };
}

function buildQuestion(item, index) {
  const letters = ['A', 'B', 'C', 'D'];
  const balancedOptions = balanceTexts(item.options, item.correct, index);
  const order = optionOrder(index);
  const orderedOptions = order.map(originalIndex => ({
    text: balancedOptions[originalIndex],
    isCorrect: originalIndex === item.correct,
    originalIndex,
  }));
  const correctLetter = letters[orderedOptions.findIndex(option => option.isCorrect)];
  const coreConcept = item.concept.split('A 对')[0].trim();
  const optionReasons = orderedOptions.map((option, optionIndex) => {
    const marker = option.isCorrect ? '对' : '错';
    return `${letters[optionIndex]} ${marker}：${reasonFor(option.isCorrect, option.text)}`;
  }).join(' ');

  return {
    id: `q-anti-pua-${String(index + 1).padStart(3, '0')}`,
    category: 'anti-pua',
    difficulty: item.difficulty,
    type: 'single',
    scenario: item.scenario,
    prompt: item.prompt,
    options: orderedOptions.map(option => ({
      text: option.text,
      isCorrect: option.isCorrect,
      explain: '',
    })),
    overallExplain: `正确答案：${correctLetter}。${coreConcept} 选项拆解：${optionReasons}`,
    tags: ['反 PUA', ...item.tags],
    relatedLevelKid: `L${String((index % 12) + 1).padStart(3, '0')}`,
  };
}

function reasonFor(isCorrect, text) {
  if (isCorrect) return '它把事实、感受和边界分开，没有急着讨好、自证或攻击。';
  if (/对不起|可能|好吧|算了|我会|我以后|我不走|我删|我付|我借|我去|我发|我换|我留下|我再|我先道歉|我可以再解释/.test(text)) {
    return '它看似缓和，但本质是在用退让、自证或补偿换取对方停止施压。';
  }
  if (/凭什么|你才|少|恶心|可笑|控制狂|装|看不上|懒得理|完就完|爱信不信|最烦|算计|没礼貌|不是你的/.test(text)) {
    return '它有反抗感，但会把重点从行为边界推成互相攻击，让操控者更容易转移话题。';
  }
  return '它像折中，实际仍然接受了对方设定的审判、监控或测试规则。';
}

