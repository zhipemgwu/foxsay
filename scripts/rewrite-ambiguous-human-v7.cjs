function enrichWrongTexts(item, questionIndex) {
  const continuations = wrongLengthContinuations[questionIndex] || [];
  return item.wrongs.map((wrong, wrongIndex) => {
    const continuation = continuations[wrongIndex];
    if (!continuation || wrong.text.includes(continuation)) return wrong;
    return { ...wrong, text: joinWrongText(wrong.text, continuation) };
  });
}

function correctLetter(options) {
  return LETTERS[options.findIndex(option => option.isCorrect)] || 'A';
}

