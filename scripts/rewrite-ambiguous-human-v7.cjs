function balanceOptions(options, label) {
  const balanced = options.map(option => ({ ...option }));
  for (let round = 0; round < 14; round++) {
    const lengths = balanced.map(option => textLen(option.text));
    const correctIndex = balanced.findIndex(option => option.isCorrect);
    const correctLen = lengths[correctIndex];
    const wrongIndexes = balanced.map((option, index) => option.isCorrect ? -1 : index).filter(index => index >= 0);
    const wrongLens = wrongIndexes.map(index => lengths[index]);
    const maxLen = Math.max(...lengths);
    const minLen = Math.min(...lengths);
    const wrongMax = Math.max(...wrongLens);
    const wrongMin = Math.min(...wrongLens);
    const pass = maxLen / Math.max(1, minLen) < 1.8
      && maxLen - minLen < 35
      && correctLen - wrongMax < 12
      && correctLen / Math.max(1, wrongMax) < 1.25
      && wrongMin - correctLen < 12
      && wrongMin / Math.max(1, correctLen) < 1.25;
    if (pass) return balanced;

    if (correctLen - wrongMax >= 12 || correctLen / Math.max(1, wrongMax) >= 1.25) {
      const target = wrongIndexes[wrongLens.indexOf(wrongMin)];
      const continuation = balanceContinuation(balanced[target], label, round + target);
      if (!continuation) break;
      balanced[target].text = `${withPeriod(balanced[target].text)}${continuation}`;
      continue;
    }

    if (wrongMin - correctLen >= 12 || wrongMin / Math.max(1, correctLen) >= 1.25) {
      balanced[correctIndex].text = `${withPeriod(balanced[correctIndex].text)}这样聊起来不会累。`;
      continue;
    }

    const target = lengths.indexOf(minLen);
    const continuation = balanced[target].isCorrect
      ? '这样聊起来不会累。'
      : balanceContinuation(balanced[target], label, round + target);
    if (!continuation) break;
    balanced[target].text = `${withPeriod(balanced[target].text)}${continuation}`;
  }
  return balanced;
}

