function buildQuestions() {
  return items.slice(0, 50).map((item, index) => {
    const options = orderOptions(item.correct, enrichWrongTexts(item, index), index);
    return {
      id: `q-ambiguous-${String(index + 1).padStart(3, '0')}`,
      category: 'ambiguous',
      difficulty: item.difficulty,
      type: 'single',
      scenario: item.scenario,
      prompt: `${item.prompt}\n当前情境：${item.scenario}`,
      options,
      overallExplain: `正确答案：${correctLetter(options)}。这题练的是暧昧理解里的分寸感。选“${options.find(option => option.isCorrect).text}”的原因是：${item.note}`,
      tags: item.tags,
      relatedLevelKid: 'L013',
    };
  });
}

function sentenceParts(text) {
  return String(text || '')
    .split(/[。！？!?]/)
    .map(part => part.trim())
    .filter(part => textLen(part) >= 8);
}

function validate(questions, updatedBank) {
  const errors = [];
  const scenarios = new Set();
  const prompts = new Set();
  const optionTexts = new Set();
  const answerCounts = [0, 0, 0, 0];
  const banned = /普通客套|今晚就该|故意晚点|继续追你|只看这句话|已经通过.+表态|回个表情|窗口还在|高分点|迷惑点|判断标准|句号后|这题要找|我想让对方马上知道我的态度|放在.+这个场景里|这句话保留了空间|在.+这件事上，我不想继续靠感觉猜|机会刚好在这里|至少话不会停在半路|不然我会觉得自己一直在外面等|我会把后面的安排也顺手接上|先把话题放轻一点|早点确认，后面才不会绕来绕去|先把态度放出来|这样她也知道我怎么想|我会先把态度说清楚/;

  for (const question of questions) {
    const baseScenario = String(question.scenario).split('；')[0];
    if (scenarios.has(baseScenario)) errors.push(`${question.id}: duplicate base scenario ${baseScenario}`);
    scenarios.add(baseScenario);
    if (prompts.has(question.prompt)) errors.push(`${question.id}: duplicate prompt`);
    prompts.add(question.prompt);
    if (question.options.length !== 4) errors.push(`${question.id}: expected 4 options`);
    const correctIndex = question.options.findIndex(option => option.isCorrect);
    if (correctIndex < 0) errors.push(`${question.id}: missing correct option`);
    if (question.options.filter(option => option.isCorrect).length !== 1) errors.push(`${question.id}: expected one correct option`);
    if (correctIndex >= 0) answerCounts[correctIndex]++;
    if (!/^正确答案：[A-D]。/.test(question.overallExplain || '')) errors.push(`${question.id}: malformed overallExplain`);
    if (/选项拆解|[A-D]\s*[对错]：/.test(question.overallExplain || '')) errors.push(`${question.id}: option breakdown in overallExplain`);

    for (const option of question.options) {
      if (banned.test(option.text)) errors.push(`${question.id}: banned phrase in option ${option.text}`);
      if (option.isCorrect && option.explain) errors.push(`${question.id}: correct explain should be empty`);
      if (!option.isCorrect && !/^❌/.test(option.explain || '')) errors.push(`${question.id}: wrong explain should start with ❌`);
      if (!option.isCorrect && textLen(option.explain) < 16) errors.push(`${question.id}: weak wrong explain`);
      if (optionTexts.has(option.text)) errors.push(`${question.id}: duplicate option text ${option.text}`);
      optionTexts.add(option.text);
      const parts = sentenceParts(option.text);
      if (new Set(parts).size !== parts.length) errors.push(`${question.id}: repeated sentence in option ${option.text}`);
    }
  }

  if (questions.length !== 50) errors.push(`expected 50 ambiguous questions, got ${questions.length}`);
  if (Math.max(...answerCounts) - Math.min(...answerCounts) > 1) {
    errors.push(`answer distribution uneven ${JSON.stringify(Object.fromEntries(LETTERS.map((letter, index) => [letter, answerCounts[index]])))}`);
  }
  if (updatedBank.length !== 400) errors.push(`updated bank expected 400, got ${updatedBank.length}`);
  const counts = new Map();
  for (const question of updatedBank) counts.set(question.category, (counts.get(question.category) || 0) + 1);
  for (const [category, count] of counts.entries()) {
    if (count !== 50) errors.push(`${category}: expected 50, got ${count}`);
  }
  if (errors.length) throw new Error(errors.slice(0, 80).join('\n'));
  console.log('AMBIGUOUS_V7_VALIDATION_PASSED');
  console.log('ANSWER_COUNTS=' + JSON.stringify(Object.fromEntries(LETTERS.map((letter, index) => [letter, answerCounts[index]]))));
}

function main() {
  const { bank, tail } = loadBank();
  const ambiguousQuestions = buildQuestions();
  let ambiguousIndex = 0;
  const updated = bank.map(question => {
    if (question.category !== 'ambiguous') return question;
    const replacement = ambiguousQuestions[ambiguousIndex++];
    if (!replacement) throw new Error(`missing ambiguous replacement at ${ambiguousIndex}`);
    return replacement;
  });
  if (ambiguousIndex !== 50) throw new Error(`replaced ${ambiguousIndex}, expected 50 ambiguous questions`);
  validate(ambiguousQuestions, updated);

  const source = [
    '/**',
    ' * FoxSay 微练习题库',
    ' * 8 大主题 x 50 题；暧昧理解已重写为 50 个独立生活场景，避免重复题和模板化选项。',
    ' */',
    '',
    "import type { Question } from '../services/quiz';",
    '',
    `export const QUIZ_BANK: Question[] = ${JSON.stringify(updated, null, 2)};`,
    '',
    tail.trimStart(),
  ].join('\n');
  fs.writeFileSync(BANK_PATH, source, 'utf8');
  console.log('AMBIGUOUS_V7_REWRITTEN');
  console.log('TOTAL_AMBIGUOUS=' + ambiguousQuestions.length);
  console.log('WROTE=' + BANK_PATH);
}

main();