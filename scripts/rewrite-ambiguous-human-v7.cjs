const fs = require('fs');
const path = require('path');

const BANK_PATH = path.join(__dirname, '..', 'src', 'data', 'quizBank.ts');
const MARKER = 'export const QUIZ_BANK: Question[] = ';
const END_MARKER = ';\n\nexport function getQuestionById';
const LETTERS = ['A', 'B', 'C', 'D'];

function loadBank() {
  const source = fs.readFileSync(BANK_PATH, 'utf8');
  const start = source.indexOf(MARKER);
  if (start < 0) throw new Error('QUIZ_BANK marker not found');
  const jsonStart = start + MARKER.length;
  const end = source.indexOf(END_MARKER, jsonStart);
  if (end < 0) throw new Error('QUIZ_BANK end marker not found');
  return { bank: JSON.parse(source.slice(jsonStart, end)), tail: source.slice(end + 2) };
}

function textLen(text) {
  return Array.from(String(text || '').replace(/\s+/g, '')).length;
}

function makeWrong(text, explain) {
  const finalExplain = textLen(explain) < 16 ? `${explain}这会让暧昧变得不自然。` : explain;
  return { text: smoothOptionText(text), isCorrect: false, explain: `❌ ${finalExplain}` };
}

function makeCorrect(text) {
  return { text: smoothOptionText(text), isCorrect: true, explain: '' };
}

function answerIndex(questionIndex) {
  return [2, 0, 3, 1][questionIndex % 4];
}

function orderOptions(correctText, wrongs, questionIndex) {
  const target = answerIndex(questionIndex);
  const correct = makeCorrect(correctText);
  const wrongOptions = wrongs.map(item => makeWrong(item.text, item.explain));
  let wrongIndex = 0;
  return [0, 1, 2, 3].map(index => (index === target ? { ...correct } : { ...wrongOptions[wrongIndex++] }));
}

function withPeriod(text) {
  return /[。！？!?]$/.test(text) ? text : `${text}。`;
}

function smoothOptionText(text) {
  const withEnd = withPeriod(String(text || '').trim());
  return withEnd.replace(/。(?=.)/gu, '，');
}

function stripFinalPunctuation(text) {
  return String(text || '').trim().replace(/[。！？!?]+$/u, '');
}

function joinWrongText(text, continuation) {
  const base = stripFinalPunctuation(text);
  const tail = stripFinalPunctuation(continuation);
  if (!tail) return withPeriod(base);
  return `${base}，${tail}。`;
}

function hashText(text) {
  let hash = 0;
  for (let index = 0; index < text.length; index++) {
    hash = (hash * 31 + text.charCodeAt(index)) | 0;
  }
  return Math.abs(hash);
}

